function updateFile(filePath) {
  let content = fs.readFileSync(filePath, 'utf8');

  // Remove the old unisex titan watch if present
  content = content.replace(/\n\s*\/\/\s*Titan Edge Classic \(Unisex\)[\s\S]*?gender:\s*'Unisex',\s*\},?\n/g, '\n');

  // Replace initial titan block
  const titanReplacement = `  // 🇮🇳 Indian Brands: Titan (20 Curated Official Timepieces)\n` +
    titanWatches.map(w => '  ' + JSON.stringify(w, null, 4).replace(/\n/g, '\n  ') + ',').join('\n');

  const pattern = /\/\/\s*🇮🇳 Indian Brands: Titan[\s\S]*?(?=\/\/\s*🇮🇳 Indian Brands: HMT)/;
  if (pattern.test(content)) {
    content = content.replace(pattern, titanReplacement + '\n\n  ');
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Successfully updated Titan watches in ${filePath}`);
  } else {
    console.error(`Pattern not matched in ${filePath}`);
  }
}

