const files = [
  'frontend/src/data/fallbackWatches.js',
  'admin/src/data/fallbackWatches.js'
];

files.forEach(filePath => {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the 2 legacy watches around line 2500 (swiss-tissot-bellissima-women and swiss-tissot-prx-35-unisex)
  const startPair = '  // Tissot Bellissima Small Lady (Women)\n  {';
  const endPair = '  // Seiko Presage Cocktail Time (Men)\n  {';
  const startPairIdx = content.indexOf(startPair);
  const endPairIdx = content.indexOf(endPair);
  if (startPairIdx !== -1 && endPairIdx !== -1 && endPairIdx > startPairIdx) {
    const toRemovePair = content.substring(startPairIdx, endPairIdx);
    content = content.replace(toRemovePair, '');
    console.log(`[${filePath}] Removed legacy pair: bellissima-women / prx-35-unisex`);
  } else {
    console.log(`[${filePath}] Could not find legacy Tissot pair: start=${startPairIdx}, end=${endPairIdx}`);
  }

  // 2. Remove the block of 15 legacy Tissot watches starting at tissot-prx-chrono-panda up to before seiko-5-gmt-ssk001-black
  const startStr = ',\n  {\n    "_id": "tissot-prx-chrono-panda"';
  const endStr = '  {\n    "_id": "seiko-5-gmt-ssk001-black"';
  const startIdx = content.indexOf(startStr);
  const endIdx = content.indexOf(endStr);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const toRemove = content.substring(startIdx, endIdx);
    content = content.replace(toRemove, '');
    console.log(`[${filePath}] Removed 15-watch legacy Tissot block before seiko`);
  } else {
    console.log(`[${filePath}] Could not find 15-watch legacy Tissot block: startIdx=${startIdx}, endIdx=${endIdx}`);
  }

  // 3. Replace the old 3-watch Tissot section under // 🇨🇭 Swiss Luxury: Tissot with the 20 official timepieces
  const tissotBlockRegex = /\/\/\s*🇨🇭 Swiss Luxury: Tissot[\s\S]*?(?=\/\/\s*🇨🇭 Swiss Luxury: Omega)/m;
  const newTissotBlock = '// 🇨🇭 Swiss Luxury: Tissot (20 Curated Official Timepieces)\n' +
    officialTissotWatches.map(w => JSON.stringify(w, null, 2)).join(',\n') + ',\n\n  ';

  if (tissotBlockRegex.test(content)) {
    content = content.replace(tissotBlockRegex, newTissotBlock);
    console.log(`[${filePath}] Replaced Tissot block with 20 official timepieces`);
  } else {
    console.log(`[${filePath}] tissotBlockRegex did not match`);
  }

  fs.writeFileSync(filePath, content, 'utf8');
});

console.log('Update Tissot watches completed.');
