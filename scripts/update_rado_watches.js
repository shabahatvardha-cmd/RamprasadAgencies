const files = [
  'frontend/src/data/fallbackWatches.js',
  'admin/src/data/fallbackWatches.js'
];

files.forEach(filePath => {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the 2 legacy watches around line 1945: 'swiss-rado-centrix-diamonds-women' and 'swiss-rado-true-square-unisex'
  const legacyPairRegex = /\s*\{\s*["']?_id["']?:\s*['"]swiss-rado-centrix-diamonds-women[\s\S]*?image:\s*['"]\/images\/watches\/rado-true-square-ceramic\.webp['"],\s*storeLocation:\s*['"]Baldev Plaza Flagship Showroom, Golghar['"],\s*inStock:\s*true,?\s*\},?/m;
  if (legacyPairRegex.test(content)) {
    content = content.replace(legacyPairRegex, '');
    console.log(`[${filePath}] Removed legacy pair: swiss-rado-centrix-diamonds-women / true-square`);
  } else {
    console.log(`[${filePath}] legacyPairRegex did not match`);
  }

  // 2. Remove the block of legacy Rado watches starting at rado-captain-cook-bronze-green up to before citizen-tsuyosa-ice-blue-sunray
  const startStr = ',\n  {\n    "id": "rado-captain-cook-bronze-green"';
  const endStr = '  {\n    "id": "citizen-tsuyosa-ice-blue-sunray"';
  const startIdx = content.indexOf(startStr);
  const endIdx = content.indexOf(endStr);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const toRemove = content.substring(startIdx, endIdx);
    content = content.replace(toRemove, '');
    console.log(`[${filePath}] Removed multi-watch legacy Rado block before citizen`);
  } else {
    console.log(`[${filePath}] Could not find multi-watch legacy Rado block: startIdx=${startIdx}, endIdx=${endIdx}`);
  }

  // 3. Remove single watch rado-ceramica-square-minimalist right before citizen-promaster-navihawk-gps-solar
  const startSingle = ',\n  {\n    "id": "rado-ceramica-square-minimalist"';
  const endSingle = '  {\n    "id": "citizen-promaster-navihawk-gps-solar"';
  const startSingleIdx = content.indexOf(startSingle);
  const endSingleIdx = content.indexOf(endSingle);
  if (startSingleIdx !== -1 && endSingleIdx !== -1 && endSingleIdx > startSingleIdx) {
    const toRemoveSingle = content.substring(startSingleIdx, endSingleIdx);
    content = content.replace(toRemoveSingle, '');
    console.log(`[${filePath}] Removed legacy single rado-ceramica-square-minimalist`);
  } else {
    console.log(`[${filePath}] Could not find legacy single rado-ceramica: start=${startSingleIdx}, end=${endSingleIdx}`);
  }

  // 4. Replace the old Rado section under // 🇨🇭 Swiss Luxury: Rado with the 20 official timepieces
  const radoBlockRegex = /\/\/\s*🇨🇭 Swiss Luxury: Rado[\s\S]*?(?=\/\/\s*🇯🇵 Japanese Precision: Seiko|\/\/\s*🇯🇵 Japanese Horology: Seiko)/m;
  const newRadoBlock = '// 🇨🇭 Swiss Luxury: Rado (20 Curated Official Timepieces)\n' +
    officialRadoWatches.map(w => JSON.stringify(w, null, 2)).join(',\n') + ',\n\n  ';

  if (radoBlockRegex.test(content)) {
    content = content.replace(radoBlockRegex, newRadoBlock);
    console.log(`[${filePath}] Replaced Rado block with 20 official timepieces`);
  } else {
    console.log(`[${filePath}] radoBlockRegex did not match`);
  }

  fs.writeFileSync(filePath, content, 'utf8');
});

console.log('Update Rado watches completed.');
