function updateRagaInFile(filePath) {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the 17 extra legacy raga entries at bottom
  content = content.replace(/,\s*\{\s*["']id["']:\s*["']raga-moments-of-joy-filigree["'][\s\S]*?raga-symphony-polished-gold-open-cuff["'][\s\S]*?description["']:\s*["'][^"']*?["']\s*\}/, '');

  // 2. Replace the 3 items at // Titan Raga (Women) with all 20
  const ragaBlock = `  // 🇮🇳 Indian Brands: Titan Raga (20 Curated Official Timepieces)\n` +
    ragaWatches.map(w => '  ' + JSON.stringify(w, null, 4).replace(/\n/g, '\n  ') + ',').join('\n');

  const pattern = /\/\/\s*Titan Raga \(Women\)[\s\S]*?(?=\/\/\s*Fastrack)/;
  if (pattern.test(content)) {
    content = content.replace(pattern, ragaBlock + '\n\n  ');
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Successfully updated Titan Raga in ${filePath}`);
  } else {
    console.error(`Pattern not matched in ${filePath}`);
  }
}

