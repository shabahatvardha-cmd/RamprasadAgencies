const isWatchInBrand = (w, slug) => {
  if (!w) return false;
  const b = (w.brand || '').toLowerCase().trim();
  const clean = (slug || '').toLowerCase().trim();
  return b === clean || b.replace(/\s+/g, '-') === clean;
};

const updateDataset = (filePath) => {
  const content = fs.readFileSync(filePath, 'utf8');
  
  // Extract watches array
  const startIndex = content.indexOf('export const FALLBACK_WATCHES = [');
  if (startIndex === -1) {
    console.error(`Could not find export in ${filePath}`);
    return;
  }
  
  // Dynamic import the current watches
  import(`file://${filePath}?t=${Date.now()}`).then(module => {
    const current = module.FALLBACK_WATCHES;
    console.log(`Current items in ${filePath}: ${current.length}`);
    
    // Filter out old Breitling
    const withoutBreitling = current.filter(w => !isWatchInBrand(w, 'breitling'));
    console.log(`Items after removing Breitling: ${withoutBreitling.length}`);
    
    // Add new 20 Breitling
    const updated = [...withoutBreitling, ...breitlingWatches];
    console.log(`Items after adding 20 Breitling: ${updated.length}`);
    
    const fileContent = `// Auto-generated Fallback Watches Dataset with strict 20-watches-per-brand architecture\nexport const FALLBACK_WATCHES = ${JSON.stringify(updated, null, 2)};\n`;
    fs.writeFileSync(filePath, fileContent, 'utf8');
    console.log(`Successfully updated ${filePath}`);
  });
};

const frontendFile = path.resolve(__dirname, '../frontend/src/data/fallbackWatches.js');
const adminFile = path.resolve(__dirname, '../admin/src/data/fallbackWatches.js');

updateDataset(frontendFile);
updateDataset(adminFile);
