// Helper to update dataset files
function updateDataset(filePath) {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove 3 early stray Citizen watches after Seiko-20 and before Casio
  const earlyStrayStart = '  {\n    "_id": "japan-citizen-tsuyosa"';
  const earlyStrayEnd = '  {\n    "_id": "japan-casio-edifice"';
  const esIdx = content.indexOf(earlyStrayStart);
  const eeIdx = content.indexOf(earlyStrayEnd);
  if (esIdx !== -1 && eeIdx !== -1 && eeIdx > esIdx) {
    content = content.substring(0, esIdx) + content.substring(eeIdx);
    console.log(`[${filePath}] Removed 3 early stray Citizen watches before Casio`);
  }

  // 2. Remove 2 stray Citizen watches after Titan Raga-20 and before Casio Sheen
  const strayStart = '  {\n    "_id": "japan-citizen-silhouette-women"';
  const strayEnd = '  {\n    "_id": "japan-casio-sheen-women"';
  const sIdx = content.indexOf(strayStart);
  const eIdx = content.indexOf(strayEnd);
  if (sIdx !== -1 && eIdx !== -1 && eIdx > sIdx) {
    content = content.substring(0, sIdx) + content.substring(eIdx);
    console.log(`[${filePath}] Removed 2 stray Citizen watches before Casio Sheen`);
  }

  // 3. Replace main Citizen section before Fastrack
  const startStr = '{\n    "id": "citizen-tsuyosa-ice-blue-sunray"';
  const endStr = '// 🇮🇳 Indian Youth Horology: Fastrack (20 Curated Official Timepieces)';

  let startIdx = content.indexOf(startStr);
  const endIdx = content.indexOf(endStr);

  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const citizenReplacement = '// 🇯🇵 Japanese Solar Precision: Citizen (20 Curated Official Timepieces)\n' +
      officialCitizenWatches.map(w => '  ' + JSON.stringify(w, null, 2).replace(/\n/g, '\n  ')).join(',\n') + ',\n\n  ';

    content = content.substring(0, startIdx) + citizenReplacement + content.substring(endIdx);
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`[${filePath}] Successfully updated official Citizen section!`);
  } else {
    console.error(`[${filePath}] Could not find startStr or endStr: startIdx=${startIdx}, endIdx=${endIdx}`);
  }
}

