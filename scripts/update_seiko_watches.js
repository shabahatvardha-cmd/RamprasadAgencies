const files = [
  'frontend/src/data/fallbackWatches.js',
  'admin/src/data/fallbackWatches.js'
];

files.forEach(filePath => {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the 2 legacy watches around line 2874 (japan-seiko-presage-women and japan-seiko-5-sports-36-unisex)
  const startPair = '  // Seiko Presage Cocktail Time Diamond Ladies (Women)\n  {';
  const endPair = '  // Citizen Silhouette Crystal (Women)\n  {';
  const startPairIdx = content.indexOf(startPair);
  const endPairIdx = content.indexOf(endPair);
  if (startPairIdx !== -1 && endPairIdx !== -1 && endPairIdx > startPairIdx) {
    const toRemovePair = content.substring(startPairIdx, endPairIdx);
    content = content.replace(toRemovePair, '');
    console.log(`[${filePath}] Removed legacy Seiko pair`);
  } else {
    console.log(`[${filePath}] Could not find legacy Seiko pair: start=${startPairIdx}, end=${endPairIdx}`);
  }

  // 2. Remove the block of 15 legacy Seiko watches starting at seiko-5-gmt-ssk001-black up to before casio-gshock-gm2100-metal-silver
  const startStr = ',\n  {\n    "_id": "seiko-5-gmt-ssk001-black"';
  const endStr = '  {\n    "_id": "casio-gshock-gm2100-metal-silver"';
  const startIdx = content.indexOf(startStr);
  const endIdx = content.indexOf(endStr);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const toRemove = content.substring(startIdx, endIdx);
    content = content.replace(toRemove, '');
    console.log(`[${filePath}] Removed 15-watch legacy Seiko block before casio`);
  } else {
    console.log(`[${filePath}] Could not find 15-watch legacy Seiko block: startIdx=${startIdx}, endIdx=${endIdx}`);
  }

  // 3. Replace the old 3-watch Seiko section under // 🇯🇵 Japanese Precision: Seiko with the 20 official timepieces
  const seikoBlockRegex = /\/\/\s*🇯🇵 Japanese Precision: Seiko[\s\S]*?(?=\/\/\s*🇯🇵 Japanese Technology: Citizen|\/\/\s*🇯🇵 Japanese Precision: Citizen)/m;
  const newSeikoBlock = '// 🇯🇵 Japanese Precision: Seiko (20 Curated Official Timepieces)\n' +
    officialSeikoWatches.map(w => JSON.stringify(w, null, 2)).join(',\n') + ',\n\n  ';

  if (seikoBlockRegex.test(content)) {
    content = content.replace(seikoBlockRegex, newSeikoBlock);
    console.log(`[${filePath}] Replaced Seiko block with 20 official timepieces`);
  } else {
    console.log(`[${filePath}] seikoBlockRegex did not match`);
  }

  fs.writeFileSync(filePath, content, 'utf8');
});

console.log('Update Seiko watches completed.');
