const files = [
  'frontend/src/data/fallbackWatches.js',
  'admin/src/data/fallbackWatches.js'
];

files.forEach(filePath => {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the 2 legacy watches: 'swiss-omega-constellation-women' and 'swiss-omega-aqua-terra-38-unisex'
  const legacyPairRegex = /\s*\/\/\s*Omega Constellation 29mm \(Women\)[\s\S]*?gender:\s*'Unisex',\s*\},/m;
  if (legacyPairRegex.test(content)) {
    content = content.replace(legacyPairRegex, '');
    console.log(`[${filePath}] Removed legacy constellation/aqua-terra pair`);
  } else {
    console.log(`[${filePath}] legacyPairRegex did not match`);
  }

  // 2. Remove the 8 legacy watches starting at "id": "omega-planet-ocean-600m-black" up to before "id": "breitling-chronomat-b01-42-anthracite"
  const legacy8Regex = /,\s*\{\s*["']id["']:\s*["']omega-planet-ocean-600m-black[\s\S]*?storeLocation["']:\s*["']Baldev Plaza Flagship Showroom, Golghar["'],\s*["']description["']:\s*["'][^"']+["']\s*\}/m;
  if (legacy8Regex.test(content)) {
    content = content.replace(legacy8Regex, '');
    console.log(`[${filePath}] Removed 8 legacy omega watches block`);
  } else {
    console.log(`[${filePath}] legacy8Regex did not match`);
  }

  // 3. Remove the single legacy watch: "id": "omega-aqua-terra-shades-atlantic-blue"
  const legacySingleRegex = /,\s*\{\s*["']id["']:\s*["']omega-aqua-terra-shades-atlantic-blue[\s\S]*?storeLocation["']:\s*["']Baldev Plaza Flagship Showroom, Golghar["'],\s*["']description["']:\s*["'][^"']+["']\s*\}/m;
  if (legacySingleRegex.test(content)) {
    content = content.replace(legacySingleRegex, '');
    console.log(`[${filePath}] Removed legacy single omega watch`);
  } else {
    console.log(`[${filePath}] legacySingleRegex did not match`);
  }

  // 4. Update the 20 official Omega timepieces block
  const omegaBlockRegex = /\/\/\s*🇨🇭 Swiss Luxury: Omega \(20 Curated Official Timepieces\)[\s\S]*?(?=\/\/\s*🇨🇭 Swiss Luxury: Breitling|\/\/\s*🇯🇵 Japanese Horology: Seiko|\/\/\s*🇨🇭 Swiss Luxury: Rado)/m;
  const newOmegaBlock = '// 🇨🇭 Swiss Luxury: Omega (20 Curated Official Timepieces)\n' +
    officialOmegaWatches.map(w => JSON.stringify(w, null, 2)).join(',\n') + ',\n\n  ';

  if (omegaBlockRegex.test(content)) {
    content = content.replace(omegaBlockRegex, newOmegaBlock);
    console.log(`[${filePath}] Replaced official Omega 20 block`);
  } else {
    console.log(`[${filePath}] omegaBlockRegex did not match`);
  }

  fs.writeFileSync(filePath, content, 'utf8');
});
console.log('Done cleaning and finalizing Omega watches.');
