function updateOmegaInFile(filePath) {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the 14 extra legacy omega entries
  content = content.replace(/,\s*\{\s*["']id["']:\s*["']omega-speedmaster-chronoscope-silver["'][\s\S]*?omega-railmaster-black-brushed["'][\s\S]*?description["']:\s*["'][^"']*?["']\s*\}/, '');

  // 2. Remove the single extra omega-speedmaster-racing-white-panda entry if present
  content = content.replace(/,\s*\{\s*["']id["']:\s*["']omega-speedmaster-racing-white-panda["'][\s\S]*?description["']:\s*["'][^"']*?["']\s*\}/, '');

  // 3. Remove the two women/unisex items if present: swiss-omega-constellation-women, swiss-omega-speedmaster-38
  content = content.replace(/,\s*\{\s*["']?_id["']?:\s*["']swiss-omega-constellation-women["'][\s\S]*?gender:\s*['"]Women['"],?\s*\},?\n/g, '\n');
  content = content.replace(/,\s*\{\s*["']?_id["']?:\s*["']swiss-omega-speedmaster-38["'][\s\S]*?gender:\s*['"]Unisex['"],?\s*\},?\n/g, '\n');

  // 4. Replace the main omega block (lines around // 🇨🇭 Swiss Luxury: Omega) with all 20 official models
  const omegaBlock = `  // 🇨🇭 Swiss Luxury: Omega (20 Curated Official Timepieces)\n` +
    omegaWatches.map(w => '  ' + JSON.stringify(w, null, 4).replace(/\n/g, '\n  ') + ',').join('\n');

  const pattern = /\/\/\s*🇨🇭 Swiss Luxury: Omega[\s\S]*?(?=\/\/\s*🇨🇭 Swiss Luxury: Breitling)/;
  if (pattern.test(content)) {
    content = content.replace(pattern, omegaBlock + '\n\n  ');
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Successfully updated Omega in ${filePath}`);
  } else {
    console.error(`Pattern not matched in ${filePath}`);
  }
}

