const files = [
  'frontend/src/data/fallbackWatches.js',
  'admin/src/data/fallbackWatches.js'
];

files.forEach(filePath => {
  let content = fs.readFileSync(filePath, 'utf8');

  // 1. Remove the legacy block of 16 HMT watches starting at "id": "hmt-kohinoor-saffron-yellow"
  const startStr = ',\n  {\n    "id": "hmt-kohinoor-saffron-yellow"';
  const endStr = '  {\n    "id": "fastrack-animal-print-street-chrono"';
  const startIdx = content.indexOf(startStr);
  const endIdx = content.indexOf(endStr);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const toRemove = content.substring(startIdx, endIdx);
    content = content.replace(toRemove, '');
    console.log(`[${filePath}] Removed multi-watch legacy HMT block before fastrack`);
  } else {
    console.log(`[${filePath}] Could not find multi-watch legacy HMT block: startIdx=${startIdx}, endIdx=${endIdx}`);
  }

  // 2. Replace the old HMT section under // 🇮🇳 Indian Brands: HMT with the 20 official timepieces
  const hmtBlockRegex = /\/\/\s*🇮🇳 Indian Brands: HMT[\s\S]*?(?=\/\/\s*🇮🇳 Indian Brands: Fastrack)/m;
  const newHmtBlock = '// 🇮🇳 Indian Heritage: HMT (20 Curated Official Timepieces)\n' +
    officialHmtWatches.map(w => JSON.stringify(w, null, 2)).join(',\n') + ',\n\n  ';

  if (hmtBlockRegex.test(content)) {
    content = content.replace(hmtBlockRegex, newHmtBlock);
    console.log(`[${filePath}] Replaced HMT block with 20 official timepieces`);
  } else {
    console.log(`[${filePath}] hmtBlockRegex did not match`);
  }

  fs.writeFileSync(filePath, content, 'utf8');
});

console.log('Update HMT watches completed.');
